"""
tests/test_dependency_lock.py
--------------------------------
One lock file, requirements.lock, for CI, the pipeline and terrain
workflows, and the Railway services (scripts/lock_requirements.py has the
model). These tests check every path still goes through it:

  - each human-edited requirements*.txt carries `-c requirements.lock`, so
    any `pip install -r` of it installs the locked versions;
  - the lock covers every package those files name (a name added without
    re-locking would install whatever is newest that day), and honours the
    deliberate pins in them;
  - the Python version is one value, .python-version, read by every
    workflow's setup-python and by Railpack, and matching the lock;
  - every workflow `pip install` goes through the lock and is followed by
    the --check-installed step;
  - railpack.json copies the lock into Railpack's install step (Railpack
    otherwise copies requirements.txt alone, so the -c line would fail)
    and checks the result in the build step;
  - --check-installed itself catches a version that is not the locked one,
    a package that was never locked, and the wrong Python.
"""

import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("lock_requirements", REPO / "scripts" / "lock_requirements.py")
lock = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lock)

PINS = lock.read_lock()
WORKFLOWS = sorted((REPO / ".github" / "workflows").glob("*.yml"))


# --- the inputs and the lock --------------------------------------------------

@pytest.mark.parametrize("name", lock.INPUTS)
def test_every_input_is_constrained_by_the_lock_before_its_first_requirement(name):
    lines = [l.split("#", 1)[0].strip() for l in (REPO / name).read_text().splitlines()]
    lines = [l for l in lines if l]
    assert lines and lines[0] == lock.CONSTRAINT_LINE, (
        f"{name}: the first non-comment line must be `{lock.CONSTRAINT_LINE}`"
    )


@pytest.mark.parametrize("name", lock.INPUTS)
def test_the_lock_covers_every_package_each_input_names(name):
    missing = [pkg for pkg in lock.requirement_names(REPO / name) if pkg not in PINS]
    assert not missing, f"{name} names {missing}, which requirements.lock does not pin -- run scripts/lock_requirements.py"


def test_deliberate_pins_in_the_inputs_are_what_the_lock_holds():
    for name in lock.INPUTS:
        for line in (REPO / name).read_text().splitlines():
            match = re.match(r"^([A-Za-z0-9._-]+)==([^\s#;]+)", line.strip())
            if match:
                assert PINS[lock.normalize(match.group(1))] == {match.group(2)}, f"{name}: {line.strip()}"


def test_the_lock_was_generated_by_the_script():
    header = (REPO / "requirements.lock").read_text().splitlines()[:2]
    assert "autogenerated" in header[0] and "scripts/lock_requirements.py" in header[1]


# --- one Python version ---------------------------------------------------------

def test_python_version_is_one_value():
    assert (REPO / ".python-version").read_text().strip() == lock.PYTHON_VERSION


@pytest.mark.parametrize("workflow", WORKFLOWS, ids=lambda p: p.name)
def test_every_workflow_reads_python_from_python_version(workflow):
    for job in yaml.safe_load(workflow.read_text())["jobs"].values():
        for step in job.get("steps", []):
            if str(step.get("uses", "")).startswith("actions/setup-python"):
                assert step["with"].get("python-version-file") == ".python-version", workflow.name
                assert "python-version" not in step["with"], f"{workflow.name}: hard-coded Python version"


# --- every workflow install goes through the lock --------------------------------

def _steps(workflow):
    for job in yaml.safe_load(workflow.read_text())["jobs"].values():
        yield from job.get("steps", [])


@pytest.mark.parametrize("workflow", WORKFLOWS, ids=lambda p: p.name)
def test_every_pip_install_is_locked_and_then_checked(workflow):
    steps = list(_steps(workflow))
    for index, step in enumerate(steps):
        run = step.get("run", "")
        if not re.search(r"\bpip install\b", run):
            continue
        files = re.findall(r"-r\s+(\S+)", run)
        assert files or "-c requirements.lock" in run, f"{workflow.name}: unlocked install: {run!r}"
        for f in files:
            assert f in lock.INPUTS, f"{workflow.name}: installs {f}, which is not a locked input"
        following = steps[index + 1] if index + 1 < len(steps) else {}
        assert "lock_requirements.py --check-installed" in following.get("run", ""), (
            f"{workflow.name}: no lock check right after {run!r}"
        )
        assert following.get("if") == step.get("if"), f"{workflow.name}: the check must run when the install does"


# --- Railway (Railpack) ------------------------------------------------------------

def test_railpack_copies_the_lock_before_its_generated_install():
    """
    Railpack's Python provider copies only requirements.txt into its install
    step and runs `pip install -r requirements.txt`; the -c line in it needs
    the lock present. "..." expands to the generated commands, so the copy
    must come before it.
    """
    config = json.loads((REPO / "railpack.json").read_text())
    install = config["steps"]["install"]["commands"]
    copy = {"src": "requirements.lock", "dest": "requirements.lock"}
    assert copy in install and "..." in install
    assert install.index(copy) < install.index("...")


def test_railpack_checks_the_install_in_its_build_step():
    build = json.loads((REPO / "railpack.json").read_text())["steps"]["build"]["commands"]
    assert build[0] == "...", "keep the generated build commands"
    assert "/app/.venv/bin/python scripts/lock_requirements.py --check-installed" in build


# --- the check itself ------------------------------------------------------------------

class _Dist:
    def __init__(self, name, version):
        self.metadata = {"Name": name}
        self.version = version


def _locked(name):
    return next(iter(PINS[lock.normalize(name)]))


def test_check_passes_on_locked_versions(capsys):
    dists = [_Dist("numpy", _locked("numpy")), _Dist("Scikit_Image", _locked("scikit-image")), _Dist("pip", "99")]
    assert lock.check_installed(dists, python=(3, 12, 7)) == 0


def test_check_fails_on_a_version_that_is_not_the_locked_one(capsys):
    assert lock.check_installed([_Dist("numpy", "0.0.1")], python=(3, 12, 7)) == 1
    assert "numpy==0.0.1" in capsys.readouterr().err


def test_check_fails_on_a_package_that_was_never_locked(capsys):
    assert lock.check_installed([_Dist("not-in-the-lock", "1.0")], python=(3, 12, 7)) == 1
    assert "never locked" in capsys.readouterr().err


def test_check_fails_on_the_wrong_python(capsys):
    assert lock.check_installed([], python=(3, 13, 2)) == 1
    assert "python 3.13.2" in capsys.readouterr().err
