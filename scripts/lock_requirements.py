#!/usr/bin/env python3
"""
scripts/lock_requirements.py
-------------------------------
One lock file, requirements.lock, for every place this repo installs Python
packages: CI, the pipeline and terrain workflows, and the Railway services.

THE MODEL
---------
- requirements.txt, requirements-pipeline.txt, requirements-terrain.txt and
  requirements-dev.txt stay the HUMAN-EDITED inputs: package names, plus a
  pin only where there is a reason (eccodeslib). Each starts with
  `-c requirements.lock`, so every `pip install -r <one of them>` -- by a
  workflow, by Railpack, by Nixpacks, by hand -- installs the exact
  versions in the lock. pip treats the lock as constraints: it never
  installs anything from it that the input file does not ask for, so each
  set stays as light as before.
- requirements.lock is GENERATED by this script: one resolution of the
  union of all four inputs, for Python PYTHON_VERSION (also in
  .python-version, which setup-python and Railpack both read). One
  resolution means numpy, scipy, shapely... are the same version
  everywhere.
- No hashes. pip turns hashes in a constraints file into hash-checking
  mode for the whole install, which then rejects the unpinned names in the
  human files. Exact versions are what make installs reproducible here.

USAGE
-----
    python3 scripts/lock_requirements.py            # re-lock, keeping existing pins
    python3 scripts/lock_requirements.py --upgrade  # deliberate upgrade: newest everything
    python3 scripts/lock_requirements.py --upgrade-package numpy   # just one
    python3 scripts/lock_requirements.py --check-installed         # does this env match the lock?

Locking needs `uv` (https://docs.astral.sh/uv/). --check-installed is stdlib
only; the workflows and the Railway build run it after installing, so an
install that did not come from the lock fails loudly.

A DELIBERATE UPGRADE is one PR: run --upgrade (or --upgrade-package), commit
the regenerated requirements.lock, and let CI run the full suite against it.
Nothing else upgrades: adding a package to an input file and re-running
without --upgrade keeps every existing pin.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LOCK = REPO / "requirements.lock"
PYTHON_VERSION = "3.12"
INPUTS = ("requirements.txt", "requirements-pipeline.txt", "requirements-terrain.txt", "requirements-dev.txt")
CONSTRAINT_LINE = "-c requirements.lock"

# Installed by Python / venv itself, not by any requirements file.
BOOTSTRAP = {"pip", "setuptools", "wheel"}

_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s;\\]+)")


def normalize(name: str) -> str:
    """PEP 503 name normalization: Scikit_Image == scikit-image."""
    return re.sub(r"[-_.]+", "-", name).lower()


def read_lock(path: Path = LOCK) -> dict[str, set[str]]:
    """{normalized name: {pinned versions}}. A universal lock can pin one
    package at different versions under different environment markers."""
    pins: dict[str, set[str]] = {}
    for line in path.read_text().splitlines():
        match = _PIN.match(line.strip())
        if match:
            pins.setdefault(normalize(match.group(1)), set()).add(match.group(2))
    return pins


def requirement_names(path: Path) -> list[str]:
    """Top-level package names in a human-edited requirements file."""
    names = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)", line)
        if match:
            names.append(normalize(match.group(1)))
    return names


def lock(extra_args: list[str]) -> int:
    uv = shutil.which("uv")
    if not uv:
        print("ERROR: locking needs uv: https://docs.astral.sh/uv/getting-started/installation/", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory() as tmp:
        # The inputs, minus their `-c requirements.lock` line: the lock must
        # not constrain its own regeneration, or --upgrade could not move it.
        for name in INPUTS:
            text = (REPO / name).read_text()
            kept = [l for l in text.splitlines() if l.strip() != CONSTRAINT_LINE]
            (Path(tmp) / name).write_text("\n".join(kept) + "\n")
        if LOCK.exists():
            shutil.copy(LOCK, Path(tmp) / LOCK.name)  # existing pins are preferences unless --upgrade
        cmd = [uv, "pip", "compile", *INPUTS, "--universal", "--python-version", PYTHON_VERSION,
               "--output-file", LOCK.name, "--custom-compile-command",
               "python3 scripts/lock_requirements.py", *extra_args]
        result = subprocess.run(cmd, cwd=tmp)
        if result.returncode == 0:
            shutil.copy(Path(tmp) / LOCK.name, LOCK)
        return result.returncode


def check_installed(distributions=None, python=None) -> int:
    """Every installed distribution is in the lock, at a locked version,
    and Python is PYTHON_VERSION. Arguments exist for the tests."""
    pins = read_lock()
    dists = [(normalize(d.metadata["Name"] or ""), d.version)
             for d in (metadata.distributions() if distributions is None else distributions)]
    dists = [(name, version) for name, version in dists if name and name not in BOOTSTRAP]
    python = python or sys.version_info[:3]
    wrong, unlocked = [], []
    for name, version in dists:
        if name not in pins:
            unlocked.append(f"{name}=={version}")
        elif version not in pins[name]:
            wrong.append(f"{name}=={version} (lock: {', '.join(sorted(pins[name]))})")
    running = ".".join(str(part) for part in python)
    if tuple(python[:2]) != tuple(int(part) for part in PYTHON_VERSION.split(".")):
        wrong.append(f"python {running} (lock: {PYTHON_VERSION}, see .python-version)")
    if wrong or unlocked:
        if wrong:
            print("NOT FROM THE LOCK -- installed version differs:\n  " + "\n  ".join(sorted(wrong)), file=sys.stderr)
        if unlocked:
            print("NOT IN THE LOCK -- installed but never locked (re-run scripts/lock_requirements.py):\n  "
                  + "\n  ".join(sorted(unlocked)), file=sys.stderr)
        return 1
    print(f"LOCK-CHECK ok: {len(dists)} installed distributions all match requirements.lock (python {running})")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--upgrade", action="store_true", help="re-resolve everything to the newest allowed")
    parser.add_argument("--upgrade-package", action="append", default=[], metavar="NAME",
                        help="re-resolve just this package (repeatable)")
    parser.add_argument("--check-installed", action="store_true",
                        help="check the running environment against the lock instead of locking")
    args = parser.parse_args(argv)
    if args.check_installed:
        return check_installed()
    extra = (["--upgrade"] if args.upgrade else []) + [f"--upgrade-package={p}" for p in args.upgrade_package]
    return lock(extra)


if __name__ == "__main__":
    sys.exit(main())
